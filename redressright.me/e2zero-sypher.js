// ─── CORE AGENT EXECUTION ───
async function executeAgent(agentId, userMessage, options = {}) {
    const provider = PROVIDERS[options.provider || document.getElementById('e2zProvider')?.value || 'openai'];
    const key = apiKeys[options.provider || document.getElementById('e2zProvider')?.value || 'openai'] || '';
    const systemPrompt = buildSystemPrompt(agentId);

    const t0 = Date.now();
    const response = await provider.call(systemPrompt, userMessage, key);
    const elapsed = Date.now() - t0;

    // SYPHPER enforcement
    const enforced = SYPHPER.enforce(response);

    // Memory
    Memory.addToHistory({
        agent: agentId,
        action: userMessage.substring(0, 100),
        summary: enforced.text.substring(0, 200),
        topic: options.topic || '',
    });

    return {
        text: enforced.text,
        violations: enforced.violations,
        agent: agentId,
        elapsed,
        provider: options.provider || document.getElementById('e2zProvider')?.value || 'openai',
    };
}

