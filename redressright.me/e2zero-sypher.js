let msgCounter = 0;
function addChatMessage(type, content, isTemporary = false, agentName = '') {
    const chat = document.getElementById('e2zChat');
    if (!chat) return '';
    const id = 'e2z-msg-' + (++msgCounter);
    const div = document.createElement('div');
    div.id = id;
    div.className = `e2z-msg e2z-msg-${type}`;

    if (type === 'agent' && !isTemporary) {
        const header = agentName ? `<div class="e2z-msg-agent">${agentName}</div>` : '';
        const speakBtn = `<button class="e2z-speak-btn" onclick="window.E2ZERO.readAloud(this.parentElement.querySelector('.e2z-msg-text').innerText)" title="Read aloud"><i class="fas fa-volume-high"></i></button>`;
        const copyBtn = `<button class="e2z-speak-btn" onclick="navigator.clipboard.writeText(this.parentElement.querySelector('.e2z-msg-text').innerText)" title="Copy"><i class="fas fa-copy"></i></button>`;
        div.innerHTML = `${header}<div class="e2z-msg-text">${formatResponse(content)}</div><div class="e2z-msg-actions">${speakBtn}${copyBtn}</div>`;
    } else {
        div.innerHTML = type === 'user' ? `<div class="e2z-msg-text">${escapeHtml(content)}</div>` : `<div class="e2z-msg-text">${content}</div>`;
    }

    chat.appendChild(div);
    chat.scrollTop = chat.scrollHeight;
    return id;
}

function formatResponse(text) {
    return escapeHtml(text)
        .replace(/\n\n/g, '<br><br>')
        .replace(/\n/g, '<br>')
        .replace(/\*\*(.+?)\*\*/g, '<strong>$1</strong>')
        .replace(/`(.+?)`/g, '<code>$1</code>');
}

function escapeHtml(str) {
    const d = document.createElement('div');
    d.textContent = str;
    return d.innerHTML;
}

