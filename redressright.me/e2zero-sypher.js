// ═══ PAGE REVIEW & HUMANIZATION MODULE ═══
// Adds to E2ZERO AGENT SYPHER
// Agents can review any page, find errors, correct in prompter's vernacular
(function() {
'use strict';

function waitForE2ZERO(cb) {
    if (window.E2ZERO) cb();
    else setTimeout(() => waitForE2ZERO(cb), 100);
}

waitForE2ZERO(function() {
    const AI_PATTERNS = [
        /\b(As an AI|I'm an AI|language model|I cannot|I don't have personal)\b/gi,
        /\b(It'?s worth noting|It'?s important to note|In conclusion|To summarize|Overall)\b/gi,
        /\b(Furthermore|Moreover|Additionally|Consequently|Nevertheless|Nonetheless)\b/gi,
        /\b(delve|utilize|leverage|facilitate|endeavor|comprehend|elucidate)\b/gi,
        /\b(paramount|plethora|myriad|multifaceted|holistic|synergy|paradigm)\b/gi,
        /\b(robust|seamless|cutting-edge|state-of-the-art|innovative|groundbreaking)\b/gi,
        /\b(I hope this helps|Let me know if|Feel free to|Don't hesitate)\b/gi,
    ];

    function getPageContent() {
        const editor = document.getElementById('editor');
        if (editor && editor.contentEditable === 'true') {
            return { element: editor, text: editor.innerText, html: editor.innerHTML, type: 'editor' };
        }
        const main = document.querySelector('main, .content, .editor-container, [role="main"], article');
        if (main) {
            return { element: main, text: main.innerText, html: main.innerHTML, type: 'content' };
        }
        return { element: document.body, text: document.body.innerText, html: document.body.innerHTML, type: 'body' };
    }

    function detectAIMarkers(text) {
        let markers = [];
        for (const pattern of AI_PATTERNS) {
            const matches = text.match(pattern);
            if (matches) markers.push(...matches.map(m => ({ phrase: m, pattern: pattern.source })));
        }
        return markers;
    }

    function buildReviewPrompt(text, mode) {
        const vernacular = window.E2ZERO.Memory.getVernacularInstruction();
        let prompt = '';
        if (mode === 'review') {
            prompt = `Review the following text for errors. Find and list:\n1. Grammar errors\n2. Spelling mistakes\n3. Punctuation issues\n4. Awkward or unclear phrasing\n5. AI-generated language patterns\n6. Incorrect legal citations\n\nFor each error: original text, corrected text, brief reason.\n${vernacular}\n\nCRITICAL: Corrections must sound human-written. Match the author's voice.\n\nTEXT TO REVIEW:\n${text.substring(0, 12000)}`;
        } else if (mode === 'humanize') {
            prompt = `Rewrite to sound completely human-written. Remove ALL AI traces:\n- Remove hedging language\n- Remove filler transitions\n- Remove AI vocabulary\n- Vary sentence length naturally\n- Use active voice\n- Keep EXACT same meaning, facts, citations\n${vernacular}\n\nOutput ONLY the rewritten text.\n\nTEXT TO HUMANIZE:\n${text.substring(0, 12000)}`;
        } else if (mode === 'proofread') {
            prompt = `Proofread and correct ONLY errors. Do NOT change style, voice, or word choice unless clear error.\nPreserve: author's voice, all legal citations, all formatting.\nFix ONLY: misspellings, grammar, punctuation, typos.\n\nOutput corrected text with NO explanations.\n\nTEXT:\n${text.substring(0, 12000)}`;
        }
        return prompt;
    }

    function addReviewButtons() {
        const body = document.querySelector('.e2z-body');
        if (!body || document.getElementById('e2z-review-section')) return;
        const section = document.createElement('div');
        section.id = 'e2z-review-section';
        section.className = 'e2z-section';
        section.innerHTML = `
            <div class="e2z-section-label">Page Tools</div>
            <div style="display:flex;flex-wrap:wrap;gap:4px">
                <button class="e2z-review-btn" onclick="window.E2ZERO.reviewPage('review')"><i class="fas fa-magnifying-glass" style="margin-right:5px"></i> Review This Page</button>
                <button class="e2z-review-btn" onclick="window.E2ZERO.reviewPage('humanize')"><i class="fas fa-feather" style="margin-right:5px"></i> Humanize Page Text</button>
                <button class="e2z-review-btn" onclick="window.E2ZERO.reviewPage('proofread')"><i class="fas fa-spell-check" style="margin-right:5px"></i> Proofread Only</button>
                <button class="e2z-review-btn" onclick="window.E2ZERO.scanAIMarkers()"><i class="fas fa-shield-halved" style="margin-right:5px"></i> Strip AI Markers</button>
            </div>`;
        const agentSection = body.querySelector('.e2z-section');
        if (agentSection && agentSection.nextSibling) body.insertBefore(section, agentSection.nextSibling);
        else body.insertBefore(section, body.firstChild?.nextSibling);
    }

    const reviewCSS = document.createElement('style');
    reviewCSS.textContent = `.e2z-review-btn{display:flex;align-items:center;padding:7px 10px;background:#1c2333;border:1px solid #2a3346;border-radius:6px;color:#ccd6f6;font-size:11px;font-weight:600;cursor:pointer;transition:all .15s;font-family:inherit}.e2z-review-btn:hover{border-color:#d4a017;color:#d4a017;background:rgba(212,160,23,.06)}`;
    document.head.appendChild(reviewCSS);

    let _msgC = 1000;
    function addMsg(type, content, isTemp, agentName) {
        const chat = document.getElementById('e2zChat');
        if (!chat) return '';
        const id = 'e2z-rv-' + (++_msgC);
        const div = document.createElement('div');
        div.id = id;
        div.className = 'e2z-msg e2z-msg-' + type;
        if (type === 'agent' && !isTemp) {
            const hdr = agentName ? '<div class="e2z-msg-agent-name">' + agentName + '</div>' : '';
            const escaped = content.replace(/&/g,'&amp;').replace(/</g,'&lt;').replace(/>/g,'&gt;').replace(/\n\n/g,'<p>').replace(/\n/g,'<br>');
            div.innerHTML = hdr + '<div class="e2z-msg-text">' + escaped + '</div>';
        } else {
            div.innerHTML = '<div class="e2z-msg-text">' + content + '</div>';
        }
        chat.appendChild(div);
        chat.scrollTop = chat.scrollHeight;
        return id;
    }

    window.E2ZERO.reviewPage = async function(mode) {
        const page = getPageContent();
        if (!page.text.trim()) { addMsg('error', 'No content found.'); return; }
        const labels = { review: 'Reviewing', humanize: 'Humanizing', proofread: 'Proofreading' };
        addMsg('system', labels[mode] + ' page (' + page.text.trim().split(/\s+/).length + ' words)...');
        const thinkId = addMsg('agent', '<div class="e2z-thinking"><div class="e2z-dot"></div><div class="e2z-dot"></div><div class="e2z-dot"></div></div>', true);
        try {
            const prompt = buildReviewPrompt(page.text, mode);
            const result = await window.E2ZERO.executeAgent('elena', prompt, {
                provider: document.getElementById('e2zProvider')?.value || document.getElementById('e2zProvider')?.value || 'openai'
            });
            document.getElementById(thinkId)?.remove();
            addMsg('agent', result.text, false, 'Elena');
            if (mode === 'humanize' || mode === 'proofread') {
                window._e2zPendingApply = { text: result.text, element: page.element, type: page.type };
                const chat = document.getElementById('e2zChat');
                const applyDiv = document.createElement('div');
                applyDiv.className = 'e2z-msg e2z-msg-system';
                applyDiv.innerHTML = '<button class="e2z-review-btn" onclick="window.E2ZERO.applyCorrection()" style="margin-top:4px"><i class="fas fa-check" style="margin-right:5px"></i> Apply to Page</button>';
                chat.appendChild(applyDiv);
                chat.scrollTop = chat.scrollHeight;
            }
        } catch(err) {
            document.getElementById(thinkId)?.remove();
            addMsg('error', 'Review failed: ' + err.message);
        }
    };

    window.E2ZERO.applyCorrection = function() {
        const pending = window._e2zPendingApply;
        if (!pending) return;
        if (pending.type === 'editor') {
            pending.element.innerHTML = '<p>' + pending.text.replace(/\n\n/g, '</p><p>').replace(/\n/g, '<br>') + '</p>';
        } else {
            addMsg('system', 'Corrected text generated. For non-editor pages, copy from above.');
        }
        addMsg('system', '✓ Correction applied.');
        window._e2zPendingApply = null;
    };

    window.E2ZERO.scanAIMarkers = function() {
        const page = getPageContent();
        const markers = detectAIMarkers(page.text);
        if (markers.length === 0) { addMsg('system', '✓ No AI markers detected.'); return; }
        addMsg('system', 'Found ' + markers.length + ' AI markers. Stripping...');
        if (page.type === 'editor') {
            let html = page.element.innerHTML;
            for (const pattern of AI_PATTERNS) html = html.replace(pattern, '');
            page.element.innerHTML = html.replace(/\s{2,}/g, ' ');
            addMsg('system', '✓ Stripped ' + markers.length + ' AI markers.');
        } else {
            const unique = [...new Set(markers.map(m => m.phrase))];
            addMsg('agent', 'AI markers found:\n' + unique.join('\n'), false, 'SYPHER');
        }
    };

    function tryInject() {
        if (document.getElementById('e2zero-sidebar')) addReviewButtons();
        else setTimeout(tryInject, 300);
    }
    tryInject();
});
})();
