// ─── FILE EXAMINATION ───
async function examineFile(file) {
    const ext = file.name.split('.').pop().toLowerCase();
    let content = '';

    if (ext === 'txt' || ext === 'md' || ext === 'html' || ext === 'htm') {
        content = await file.text();
        if (ext === 'html' || ext === 'htm') {
            const parser = new DOMParser();
            const doc = parser.parseFromString(content, 'text/html');
            content = doc.body.innerText;
        }
    } else if (ext === 'docx' && typeof mammoth !== 'undefined') {
        const ab = await file.arrayBuffer();
        const result = await mammoth.extractRawText({ arrayBuffer: ab });
        content = result.value;
    } else if (ext === 'pdf' && typeof pdfjsLib !== 'undefined') {
        const ab = await file.arrayBuffer();
        const pdf = await pdfjsLib.getDocument({ data: ab }).promise;
        for (let i = 1; i <= pdf.numPages; i++) {
            const page = await pdf.getPage(i);
            const tc = await page.getTextContent();
            content += tc.items.map(item => item.str).join(' ') + '\n';
        }
    } else {
        content = await file.text();
    }

    return { name: file.name, format: ext, content, size: file.size };
}

// ─── SPEECH TO TEXT ───
let speechRecognition = null;
let isRecording = false;

function startSpeechToText(callback) {
    if (!('webkitSpeechRecognition' in window) && !('SpeechRecognition' in window)) {
        throw new Error('Speech recognition not supported');
    }
    const SR = window.SpeechRecognition || window.webkitSpeechRecognition;
    speechRecognition = new SR();
    speechRecognition.continuous = true;
    speechRecognition.interimResults = true;
    speechRecognition.lang = 'en-US';

    let final = '';
    speechRecognition.onresult = (e) => {
        let interim = '';
        for (let i = e.resultIndex; i < e.results.length; i++) {
            if (e.results[i].isFinal) final += e.results[i][0].transcript + ' ';
            else interim += e.results[i][0].transcript;
        }
        callback({ final, interim, combined: final + interim });
    };
    speechRecognition.onend = () => { if (isRecording) speechRecognition.start(); };
    speechRecognition.start();
    isRecording = true;
}

function stopSpeechToText() {
    speechRecognition?.stop();
    isRecording = false;
}

// ─── TEXT TO SPEECH ───
function speak(text, options = {}) {
    if (window.speechSynthesis.speaking) { window.speechSynthesis.cancel(); return false; }
    const u = new SpeechSynthesisUtterance(text);
    u.rate = options.rate || 0.95;
    u.pitch = options.pitch || 1;
    if (options.onEnd) u.onend = options.onEnd;
    window.speechSynthesis.speak(u);
    return true;
}

